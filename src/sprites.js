export function drawSprite(ctx, rows, x, y, flip = false, pal = PAL) {
  const w = rows[0].length;
  for (let j = 0; j < rows.length; j++) { const r = rows[j];
    for (let i = 0; i < w; i++) { const ch = r[i]; if (ch === '.') continue; ctx.fillStyle = pal[ch] || ch;
      ctx.fillRect(Math.round(x + (flip ? w - 1 - i : i)), Math.round(y + j), 1, 1); } }
}
